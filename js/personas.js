/* 채점 지시문 — speed(수신의 신속성)와 hangup(끊는 순서)은 어플이 직접 계산한다 */
function buildEvalPrompt(caseObj, transcript) {
  const p = PERSONAS[caseObj.id];
  const aiItems = RUBRIC.filter(r => r.key !== 'speed' && r.key !== 'hangup');
  const rubricText = aiItems.map(r =>
    `- ${r.key} (${r.name}, ${r.max}점): ` +
    Object.keys(r.levels).map(Number).sort((a, b) => b - a).map(s => `${s}점=${r.levels[s]}`).join(' / ')
  ).join('\n');
  const intakeText = INTAKE_CHECKS.map(r =>
    `- ${r.key} (${r.name}): ` + Object.keys(r.levels).map(Number).sort((a, b) => b - a).map(s => `${s}=${r.levels[s]}`).join(' / ')
  ).join('\n');
  const checklistText = p.checklist
    ? '\n위기 사례 체크리스트(각 항목을 상담자가 했으면 true):\n' + p.checklist.map(c => `- ${c.key}: ${c.name}`).join('\n')
    : '';
  const convo = transcript.map(t => `${t.who === 'me' ? '상담자' : '보호자'}: ${t.text}`).join('\n');

  return [
    '너는 청소년상담1388 전화상담 모니터링 평가지표로 "연습 통화"를 채점하는 교육 도우미다.',
    '결과는 교육용 참고자료이며, 위기 여부를 판정하지 않는다.',
    `사례: ${caseObj.title} (${caseObj.who}). ${caseObj.intro}`,
    '정해진 첫인사는 "안녕하세요, 청소년전화 1388입니다. 무엇을 도와드릴까요?"이며, 인사말과 소속을 모두 말하면 greet 10점이다.',
    '',
    '평가지표(점수는 반드시 아래에 적힌 값 중 하나):',
    rubricText,
    '',
    '기관 접수 확인(평가지표 외, 0·1·2 중 하나):',
    intakeText,
    checklistText,
    '',
    '통화 기록(음성 인식이라 오타가 있을 수 있으니 뜻을 기준으로 판단):',
    convo,
    '',
    '아래 JSON 형식으로만 답한다. 설명 문장을 JSON 밖에 쓰지 않는다.',
    '{',
    '  "items": { "<항목 key>": { "score": 숫자, "reason": "판단 근거 한두 문장", "quote": "근거가 된 상담자 발화(없으면 빈 문자열)", "better": "더 나은 표현 예시 한 문장" } },',
    '  "intake": { "consent": 0|1|2, "history": 0|1|2 },',
    p.checklist ? '  "checklist": { "<체크리스트 key>": true|false },' : '',
    '  "good": ["잘한 점 1~3개"],',
    '  "improve": ["고칠 점 1~3개"]',
    '}',
    `items에는 다음 key를 모두 넣는다: ${aiItems.map(r => r.key).join(', ')}`
  ].filter(line => line !== '').join('\n');
}

